// ==================== 二、洗牌袋无放回抽样算法（Shuffle-Bag + 跨轮边界防重） ====================

/**
 * 存储每个角色、每种情绪当前的洗牌袋状态：
 * key: `${charId}_${mood}` -> { bag: [乱序索引数组], lastIdx: 上一次抽出的索引 }
 */
const _prayerShuffleBags = {};

/**
 * Fisher-Yates 标准公平洗牌算法
 */
function _fisherYatesShuffle(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const temp = arr[i];
    arr[i] = arr[j];
    arr[j] = temp;
  }
  return arr;
}

/**
 * 获取角色下一句不重复的祷告词及对应音频序号
 * - 原理：将 0 ~ 29 共 30 个索引打乱放入袋中，每次调用弹出 1 个。
 * - 在 30 次调用内 100% 不会出现任何重复；
 * - 当袋子抽空重新洗牌时，若新袋子第一句恰好等于上一轮最后一句，则将其与袋底元素交换，彻底杜绝跨轮连重。
 *
 * @param {string} charId 角色ID (如 "abraham", "david")
 * @param {string} mood 情绪 ("positive" | "negative")
 * @returns {{ quoteIdx: number, quoteText: string }}
 */
function getNextPrayerQuote(charId, mood = "positive") {
  const charPrayers = CHARACTER_PRAYERS[charId] || CHARACTER_PRAYERS.abraham;
  const moodKey = mood === "negative" ? "negative" : "positive";
  const pool = charPrayers[moodKey];
  const bagKey = `${charId}_${moodKey}`;

  if (!_prayerShuffleBags[bagKey]) {
    _prayerShuffleBags[bagKey] = { bag: [], lastIdx: -1 };
  }

  const state = _prayerShuffleBags[bagKey];

  // 如果洗牌袋已空，重新装入 0 ~ (pool.length - 1) 并进行 Fisher-Yates 洗牌
  if (state.bag.length === 0) {
    const indices = Array.from({ length: pool.length }, (_, i) => i);
    _fisherYatesShuffle(indices);

    // 跨轮边界防重：由于 pool.shift() 从数组头部取元素，若头部元素恰好等于上一轮最后一次取出的索引，则与尾部交换
    if (indices.length > 1 && indices[0] === state.lastIdx) {
      const swapPos = indices.length - 1;
      const tmp = indices[0];
      indices[0] = indices[swapPos];
      indices[swapPos] = tmp;
    }

    state.bag = indices;
  }

  const quoteIdx = state.bag.shift();
  state.lastIdx = quoteIdx;

  return {
    quoteIdx,
    quoteText: pool[quoteIdx]
  };
}

/**
 * 新开一局游戏时可调用此函数重置所有角色的洗牌袋（可选）
 */
function resetPrayerShuffleBags() {
  for (const key in _prayerShuffleBags) {
    delete _prayerShuffleBags[key];
  }
}